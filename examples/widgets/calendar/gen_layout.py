# Regenerates layout.xml: python gen_layout.py layout.xml
import sys
out = sys.argv[1]
rows = []
for r in range(6):
    cells = []
    for c in range(7):
        i = r * 7 + c
        cells.append(
            f'      <stack class="day"><ellipse class="today" if="cal.t{i}"/>'
            f'<text class="num" if="!cal.t{i}" value="{{cal.d{i}}}" color="{{cal.c{i}}}"/>'
            f'<text class="num now" if="cal.t{i}" value="{{cal.d{i}}}"/></stack>')
    cond = ' if="cal.row5"' if r == 5 else ''
    rows.append(f'    <row class="week"{cond}>\n' + '\n'.join(cells) + '\n    </row>')
heads = '\n'.join(f'      <stack class="day"><text class="head" value="{{cal.wd{c}}}"/></stack>' for c in range(7))
xml = f'''<widget xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="../../schemas/layout.xsd">
  <!-- Month view in the style of the macOS Calendar widget. Generated by a script; the grid is
       42 cells bound to the built-in cal.* values (cal.d = day, cal.t = today, cal.c = color). -->
  <style class="day" grow="1" height="fill"/>
  <style class="week" width="fill" grow="1"/>
  <style class="heads" width="fill" height="16"/>
  <style class="now" weight="700" color="#FFFFFF"/>
  <style class="num" size="11" weight="600" features="tnum"/>
  <style class="head" size="9" weight="700" color="secondary"/>
  <style class="today" width="19" height="19" fill="#FF3B30"/>
  <column padding="11 10 9 10">
    <text value="{{cal.month}}" size="11" weight="700" tracking="0.4" color="#FF3B30" padding="0 4 4 4"/>
    <row class="heads">
{heads}
    </row>
{chr(10).join(rows)}
  </column>
</widget>
'''
open(out, 'w', encoding='utf8').write(xml)
print('ok')
